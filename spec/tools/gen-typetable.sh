#!/usr/bin/env bash
# gen-typetable — regenerate Boru/Core/TypeTable.lean from the kernel's own
# builtin declaration table (core/go/typetable.go, `builtinDecls`).
#
# The lattice is DATA the kernel owns, so the spec does not restate it by
# hand: this script reads the Go table and writes the Lean one, and
# `make -C spec verify-typetable` fails when the committed file is not what
# the script produces. That is what makes "the spec's lattice is the
# kernel's lattice" a checked fact rather than a claim.
#
# Usage: tools/gen-typetable.sh [--check]
set -euo pipefail
here="$(cd "$(dirname "${BASH_SOURCE[0]}")" && pwd)"
repo="$(cd "$here/../.." && pwd)"
src="$repo/core/go/typetable.go"
out="$here/../Boru/Core/TypeTable.lean"

gen() {
  cat <<'HDR'
/-
  GENERATED by spec/tools/gen-typetable.sh from core/go/typetable.go
  (`builtinDecls`). Do not edit: change the Go table and regenerate.
-/
import Boru.Core.Lattice

namespace Boru.Core

/-- The kernel's builtin type declarations, in declaration order (parents
    before children). -/
def builtinDecls : List TypeDecl := [
HDR
  awk '
    /^var builtinDecls = \[\]builtinDecl\{/ { on = 1; next }
    on && /^\}/ { on = 0 }
    on && /\{Path:/ {
      line = $0
      path = ""; id = ""; rank = ""; parent = ""; alias = ""; internal = "false"
      if (match(line, /Path: "[^"]*"/))       { path = substr(line, RSTART + 7, RLENGTH - 8) }
      if (match(line, /FixedID: [0-9]+/))     { id = substr(line, RSTART + 9, RLENGTH - 9) }
      if (match(line, /Rank: [0-9_]+/))       { rank = substr(line, RSTART + 6, RLENGTH - 6); gsub(/_/, "", rank) }
      if (match(line, /ParentPath: "[^"]*"/)) { parent = substr(line, RSTART + 13, RLENGTH - 14) }
      if (match(line, /Alias: "[^"]*"/))      { alias = substr(line, RSTART + 8, RLENGTH - 9) }
      if (line ~ /IsInternal: true/)          { internal = "true" }
      if (parent == "") {
        n = split(path, parts, "/")
        if (n > 1) { parent = parts[1]; for (i = 2; i < n; i++) parent = parent "/" parts[i] }
      }
      p = (parent == "") ? "none" : "some \"" parent "\""
      a = (alias == "") ? "none" : "some \"" alias "\""
      printf "%s  { path := \"%s\", parent := %s, fixedId := %s, rank := %s, internal := %s, alias := %s }", sep, path, p, id, rank, internal, a
      sep = ",\n"
    }
    END { printf "\n" }
  ' "$src"
  cat <<'FTR'
]

end Boru.Core
FTR
}

if [ "${1:-}" = "--check" ]; then
  tmp="$(mktemp)"; trap 'rm -f "$tmp"' EXIT
  gen > "$tmp"
  if ! diff -u "$out" "$tmp" >/dev/null; then
    echo "spec: Boru/Core/TypeTable.lean is stale against core/go/typetable.go — run spec/tools/gen-typetable.sh" >&2
    diff -u "$out" "$tmp" | head -40 >&2
    exit 1
  fi
  echo "spec: TypeTable.lean matches core/go/typetable.go"
else
  gen > "$out"
  echo "wrote $out"
fi
